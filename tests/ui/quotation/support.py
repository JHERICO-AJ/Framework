"""Shared flows of the Quotation UI tests (so no test module imports from another test module)."""
from __future__ import annotations

import re

from playwright.sync_api import expect


def pick_first_enabled_day(page, field):
    """Opens the custom date picker and picks the first enabled day of the month shown (for the end date that is
    the start date itself, since earlier days are disabled)."""
    field.click()
    cell = page.locator(".react-datepicker__day:not(.react-datepicker__day--outside-month)"
                        ":not(.react-datepicker__day--disabled)").first
    cell.wait_for(timeout=5000)
    cell.click()
    page.keyboard.press("Escape")


def submit_a_full_quotation(quotation_page, wo_number, quote_number=None, labor_cost="50", before_submit=None, zero_prefilled=False, attempts=6):
    """Fills every field required for a real, successful Submit (WO Snapshot + the minimum Statement of FSE
    Resource / Labor Costs fields) and returns the Quote # / WO Number. Since the 2026-10 build the Quote # is
    generated by the system (read-only), the Est. Start/End Time are custom date pickers, and GSP # / Alarm ID,
    OEM Name and Est. End Time are required. "Save without approver" is clicked only if the approver modal shows.
    labor_cost sets the total; before_submit is an optional callback run just before pressing Submit (HU-16 uses
    it to assign signers). zero_prefilled=True zeroes the Site's pre-filled costs."""
    page = quotation_page.page
    wo = quotation_page.create_quotation().wo_snapshot()
    # the stories use the customer Andes Renewables SpA with the site Valle Verde; since the 2026-11 data the first customer of the list is "#Grid Test" (no business unit: the approver
    # panel then has no directory search), so the customer is chosen by name and the first one is only the fallback
    customer = wo.field("Customer")
    try:
        customer.select_option(label=re.compile(r"Andes Renewables"))
    except Exception:
        customer.select_option(index=1)
    site_options = wo.field("Site Name").locator("option")
    expect(site_options).not_to_have_count(1)
    try:
        wo.field("Site Name").select_option(label=re.compile(r"Valle Verde"))
    except Exception:
        wo.field("Site Name").select_option(index=1)
    wo.field("WO Title").fill(f"Workflow Progress test {wo_number}")
    wo.field("Type of Work").select_option(index=1)
    gsp = wo.field("GSP #")
    if gsp.is_enabled():            # since the 2026-10-20 build (HU-26) the GSP # is generated by the system and read-only
        gsp.fill(wo_number)
    wo.field("OEM Name").fill("Workflow Progress Test OEM")
    expect(wo.field("Quote # / WO Number")).not_to_have_value("", timeout=15000)   # generated by the system, may load a moment later
    generated_quote_number = wo.field("Quote # / WO Number").input_value()
    assert generated_quote_number, "the system should generate the Quote # / WO Number"

    fse = quotation_page.fse_arrangement()
    STMT = "Statement of FSE Resource"
    LABOR = "Labor Costs"
    fse.field(STMT, "Support Engineers").fill("2")
    fse.field(STMT, "Working Hour / Tech Day").fill("8")
    fse.field(STMT, "Estimated Working Days").fill("2")
    pick_first_enabled_day(page, fse.field(STMT, "Est. Start Time"))
    pick_first_enabled_day(page, fse.field(STMT, "Est. End Time"))
    if zero_prefilled:
        # choosing a Site pre-fills the customer's rates (hotel, per diem, air, car): zero them so that the total
        # is only labor (labor_cost x 8 h x 2 engineers x 2 days) and the amount can be controlled exactly
        for section, label in [("Onsite Support Costs", "Hotel Cost"), ("Onsite Support Costs", "Per Diem / Person"),
                               ("Reimbursable Costs", "Air Transportation"), ("Reimbursable Costs", "Car Expense")]:
            fse.field(section, label).fill("0")
    fse.field(LABOR, "Labor Cost / Hour").fill(str(labor_cost))
    page.wait_for_timeout(300)
    if before_submit is not None:
        before_submit()

    save_without = page.get_by_role("button", name="Save without approver", exact=False)
    submit_btn = page.get_by_role("button", name="Submit Quotation", exact=True)
    server_error_toast = page.get_by_text("Server Error", exact=False)
    form_marker = page.get_by_text("WO Snapshot", exact=True)

    # The shared QA environment intermittently returns a transient "Server Error" toast on Submit: retry rather
    # than failing on infra flakiness. Ground truth for "we left the form" is the WO Snapshot marker disappearing.
    for attempt in range(attempts):
        if attempt > 0:
            page.keyboard.press("Escape")
            page.wait_for_timeout(300)
        if submit_btn.count() == 0 or not submit_btn.first.is_visible():
            break
        submit_btn.click(force=True)
        page.wait_for_timeout(5000)
        if save_without.count() > 0:
            save_without.click()
            page.wait_for_timeout(2000)
        if form_marker.count() == 0:
            break
        if server_error_toast.count() > 0:
            page.wait_for_timeout(4000)
    expect(form_marker).to_have_count(0, timeout=40000)
    return generated_quote_number


