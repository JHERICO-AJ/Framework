_API_SESSIONS = {}


def _api_sessions():
    """One API session per role (AM, FPM, BU, CEO), created once per process; the same accounts the screen tests log in with."""
    if not _API_SESSIONS:
        from framework_api.client.role_session import RoleApiSession
        from shared.config.credentials import load_role_credentials
        for role in ("AM", "FPM", "BU", "CEO"):
            creds = load_role_credentials(role)
            if creds is None:
                import pytest
                pytest.skip(f"QUOTATION_{role}_EMAIL / QUOTATION_{role}_PASSWORD not set in .env")
            _API_SESSIONS[role] = RoleApiSession(creds["email"], creds["password"])
    return _API_SESSIONS


def submit_for_approval(am_page, tag, route, labor_cost="50"):
    """The AM sends a full quotation whose only signers are the given approvers (route = ["FPM"], ["BU", "CEO"], ...). Total stays under $100,000, so the amount rules add nobody.
    Returns (quote_no, title); the title is unique, which is how every later step finds the quotation in a list.
    Since the 2026-11-09 build the screen no longer lets the AM search and add approvers by hand (HU-16: the route comes from the default rules and the AM account), so the quotation is
    created and sent through the API with that route; the screen tests start from the approver's side. `am_page` and `labor_cost` are kept so the callers do not change."""
    from framework_api.services import quotation_setup as qs
    sessions = _api_sessions()
    quotation_id, quote_no = qs.create_and_submit(sessions["AM"], sessions, tag, list(route), title_prefix="HU22")
    title = sessions["AM"].get(f"/api/quotations/{quotation_id}").json()["title"]
    return quote_no, title


def open_as_approver(role_page, role, title):
    """The approver (role: 'FPM' | 'BU' | 'CEO') opens the quotation from the Pending approval list."""
    from framework_ui.pages.quotation.quotation_page import QuotationPage
    qp = QuotationPage(role_page(role)).open(refresh=True)
    qp.open_listed_quotation(title)
    return qp
