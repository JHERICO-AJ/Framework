# --- HU-08: length of the free-text fields (Qase #961, defect #143 / OP-113: fixed, verified 2026-11-06) ---
# The browser stops typing at the limit, but the limit can be removed with the developer tools. The server must answer HTTP 400 with a field-level
# message for a value one character longer, never HTTP 500. Checked through the API (the screen test no longer captured the request). GSP # is not
# in the list any more: the server generates it (HU-26) and ignores what the client sends.
_LENGTH_FIELDS = [("oemName", 200), ("title", 300), ("siteLocation", 500), ("unitInfo", 200), ("device", 200)]


@pytest.mark.parametrize("field, limit", _LENGTH_FIELDS, ids=[f[0] for f in _LENGTH_FIELDS])
def test_text_longer_than_the_field_limit_is_rejected_with_a_validation_error_not_a_500(api_roles, make_draft, field, limit):
    quotation_id, _ = make_draft(f"LEN{field}", title_prefix="HU08-LEN")
    am = api_roles["AM"]
    body = am.get(f"/api/quotations/{quotation_id}").json()
    url = f"{am.base_url}/api/quotations/{quotation_id}"
    body[field] = "A" * limit
    assert am.session.put(url, json=body, timeout=90).status_code == 200, "a value exactly at the limit must be accepted"
    body[field] = "A" * (limit + 1)
    response = am.session.put(url, json=body, timeout=90)
    assert response.status_code == 400, f"expected HTTP 400 with a validation message, got {response.status_code}: {response.text[:150]}"
    assert field in response.text, "the validation message must name the field"
