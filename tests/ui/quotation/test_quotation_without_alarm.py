"""Quotation module -- creating a quotation, what is left of HU-01 (Jira OP-16 "Quotation pre-fill from the OmniOps alarm module", Qase suite 38, cases PF-*). Regression of 2026-11-10 as the AM.

Scope decision (2026-11-10): a quotation can no longer be created from an alarm (the alarm details offer Events History and Copy SOP only), so AC #1, #2, #4, #5 and #6 of OP-16, and the bugs
OP-35 (customer) and OP-36 (deleted alarm), have no path to exercise; the 10 old cases were deprecated. What stays:
  - AC #3 / OP-37: a quotation without alarm source. The story says the field shows "--"; the developer changed that in a comment of OP-37 ("we will modify the acceptance criteria to accept a
    placeholder, just not the one defined in the user story") and the application shows "Generated on save" (HU-26 makes the GSP # generated by the system, locked). We follow the comment.
  - AC #1 / #5 / #6 read on the only path that remains, the module's own Create Quotation button: the form opens at once, blank and editable (deduced from the story, said so in the cases).
  - A guard: the alarm details do not offer Create Quotation. If it comes back, HU-01 is in scope again.
Each test that saves a Draft puts a timestamp in its title (the system refuses two equal quotations)."""
import re
import time

import pytest
from playwright.sync_api import expect

from framework_ui.pages.quotation import quotation_locators as qloc
from framework_ui.pages.quotation.components import wo_snapshot_locators as loc

from tests.ui.quotation.am_page import quotation_page  # noqa: F401  (runs as the AM)

pytestmark = pytest.mark.ui

PLACEHOLDER = "Generated on save"
TYPED_FIELDS = [loc.LABEL_OEM_NAME, loc.LABEL_WO_TITLE, "Unit Info", "Device"]


@pytest.fixture
def wo_snapshot(quotation_page):
    snapshot = quotation_page.create_quotation().wo_snapshot()
    yield snapshot
    quotation_page.close_form()


def test_a_quotation_without_alarm_shows_the_placeholder_in_gsp(wo_snapshot):
    """Qase PF-1 (AC #3, OP-37) -- GSP # is empty, locked and shows 'Generated on save' (the accepted placeholder; the story's '--' was changed by the developer)."""
    gsp = wo_snapshot.field(loc.LABEL_GSP_ALARM_ID)
    assert gsp.input_value() == ""
    assert gsp.get_attribute("placeholder") == PLACEHOLDER
    assert gsp.is_disabled(), "the GSP # is generated by the system: it cannot be typed"


def test_after_saving_the_gsp_number_is_generated_and_kept_when_reopened(quotation_page, api_roles):
    """Qase PF-2 (AC #3, OP-37 steps 3-4) -- once the quotation has its customer, site and type of work the system generates the GSP #; after Save Draft it is the number the system stores and it is
    still there when the quotation is reopened. (Checked 2026-11-10: with only OEM Name and WO Title the draft is saved with no GSP # yet.)"""
    page = quotation_page.page
    wo = quotation_page.create_quotation().wo_snapshot()
    title = f"HU01 GSP test {int(time.time())}"
    wo.field(loc.LABEL_OEM_NAME).fill("HU01 OEM")
    wo.field(loc.LABEL_WO_TITLE).fill(title)
    wo.field("Customer").select_option(index=1)
    expect(wo.field("Site Name").locator("option")).not_to_have_count(1)
    wo.field("Site Name").select_option(index=1)
    wo.field("Type of Work").select_option(index=2)
    expect(wo.field(loc.LABEL_GSP_ALARM_ID)).not_to_have_value("", timeout=15000)
    shown = wo.field(loc.LABEL_GSP_ALARM_ID).input_value()
    quotation_page.save_draft()
    page.get_by_text(qloc.FORM_LOADED_MARKER_TEXT, exact=True).wait_for(state="hidden", timeout=15000)
    stored = api_roles["AM"].get("/api/quotations", page=1, pageSize=5, includeClosed="false", search=title).json()["items"]
    assert len(stored) == 1 and stored[0]["gsp"] == shown, f"the form showed {shown!r}, the system stores {[i['gsp'] for i in stored]}"
    page.get_by_text(title, exact=True).click()
    page.get_by_text(qloc.FORM_LOADED_MARKER_TEXT, exact=True).wait_for(timeout=15000)
    reopened = quotation_page.wo_snapshot().field(loc.LABEL_GSP_ALARM_ID)
    assert reopened.input_value() == shown and reopened.is_disabled()
    quotation_page.close_form()


def test_create_quotation_opens_a_blank_form_that_can_be_edited(wo_snapshot):
    """Qase PF-3 (AC #1, #5, #6 on the remaining path) -- one click on Create Quotation opens the form; the text fields are empty and enabled, and they take what is typed."""
    for label in TYPED_FIELDS:
        field = wo_snapshot.field(label)
        assert field.input_value() == "", f"{label} is not blank"
        assert field.is_enabled() and field.is_editable(), f"{label} cannot be edited"
        field.fill("typed by the AM")
        assert field.input_value() == "typed by the AM"
        field.fill("")


def test_the_alarm_details_do_not_offer_create_quotation(quotation_page):
    """Qase PF-4 (scope of HU-01) -- the alarm details (Alarms & Events, Last 30 days) have no 'Create Quotation' action, so a quotation cannot start from an alarm. If this fails, HU-01 is in scope again."""
    page = quotation_page.page
    page.locator("a.nav-item", has_text="Alarms & Events").click()
    page.wait_for_timeout(2000)
    page.get_by_role("combobox").nth(1).select_option(label="Last 30 days")
    page.wait_for_timeout(3500)
    alarm = page.locator("button, [role=row], tr, div").filter(has_text=re.compile(r"^\s*PCS|EMS|Overvoltage|Comm Lost", re.I)).first
    if alarm.count() == 0:
        pytest.skip("needs an alarm in the list of the last 30 days to open its details")
    alarm.click()
    page.wait_for_timeout(2000)
    assert page.get_by_text("ALARM DETAILS & SOP").count() > 0, "the alarm details did not open"
    assert page.get_by_role("button", name=re.compile("Create Quotation", re.I)).count() == 0
    quotation_page.open()
