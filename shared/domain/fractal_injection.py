"""
fractal_injection.py — turns fractal_alarm_catalog entries into the exact
YAML text a Fractal simulator instance (simulator/fractal_site_state.py, in
the separate omniops-bess-edge repo each teammate runs locally for their own
site) hot-reloads to activate an alarm condition -- confirmed live 2026-09-16
no simulator restart is needed, so this module only needs to WRITE the file.

This is the Fractal counterpart to shared/domain/injection.py (EPC), but the
underlying mechanism is completely different: EPC injection overrides live
Modbus register reads through tools/sim_proxy.py; Fractal injection instead
edits a YAML config file the simulator's OWN process reads directly. There is
no proxy involved and no register-level math here -- just building the same
`pcs: N: analog:/bits:` / `emu: bits:` structure the real YAML file uses
(see the internal QA note 'fractal-knapp-kiruna.faults' for a hand-written example of this
same shape).

Each teammate has their own site(s) and their own local YAML file for it
(the shared example is named for a teammate's KIRUNA site) -- there's no
single "the" file path, so callers must pass their own.
"""
from __future__ import annotations

from shared.domain.fractal_alarm_catalog import BY_RULE_ID


def yaml_text_for(rule_ids, use_alt=None):
    """Builds the YAML text block that activates the given Fractal alarm
    IDs, merging overrides for the same pcs_index/emu together (so asking
    for two alarms on the same PCS produces one `pcs: N:` block, not two
    conflicting ones -- matches how a hand-edited YAML file would look).

    `use_alt`: optional set of rule_ids that should use their `inject_alt`
    variant instead of `inject` (e.g. alarm #70's confirmed-broken EMU-side
    path, kept in the catalog specifically to re-prove it's still broken).
    Raises KeyError via BY_RULE_ID lookup for an unknown ID -- deliberately
    not swallowed, since injecting the wrong/no alarm silently would be
    worse than a loud failure here."""
    use_alt = use_alt or set()
    pcs_analog = {}   # {pcs_index: {field: value}}
    pcs_bits = {}      # {pcs_index: {word: set(bits)}}
    emu_bits = {}      # {word: set(bits)}
    notes = []

    for rid in rule_ids:
        alarm = BY_RULE_ID[rid]
        variant_key = "inject_alt" if rid in use_alt else "inject"
        inject = alarm.get(variant_key)
        if inject is None:
            raise KeyError(f"alarm {rid} has no {variant_key!r} variant defined")

        pcs_index = alarm["pcs_index"]
        notes.append(f"# --- {rid} ({alarm['name']}) ---")

        if "analog" in inject:
            if pcs_index is None:
                raise ValueError(f"alarm {rid} has an 'analog' override but no pcs_index")
            pcs_analog.setdefault(pcs_index, {}).update(inject["analog"])

        if "bits" in inject:
            if pcs_index is None:
                raise ValueError(f"alarm {rid} has a 'bits' override but no pcs_index")
            bucket = pcs_bits.setdefault(pcs_index, {})
            for word, bits in inject["bits"].items():
                bucket.setdefault(word, set()).update(bits)

        if "emu_bits" in inject:
            for word, bits in inject["emu_bits"].items():
                emu_bits.setdefault(word, set()).update(bits)

        if "meter_total_active_power_kw_factor" in inject:
            notes.append(
                f"#   (meter mismatch: no simulator override needed -- the "
                f"sim's own transformer loss already exceeds tolerance; "
                f"see alarm {rid}'s catalog note for the real blocker)")

    lines = ["# Generated by shared/domain/fractal_injection.py -- DO NOT hand-edit,",
             "# regenerate instead. Comment/replace lines here as needed for manual tweaks.",
             ""]

    all_pcs = sorted(set(pcs_analog) | set(pcs_bits))
    if all_pcs:
        lines.append("pcs:")
        for idx in all_pcs:
            lines.append(f"  {idx}:")
            analog = pcs_analog.get(idx, {})
            if analog:
                lines.append("    analog:")
                for field, value in analog.items():
                    lines.append(f"      {field}: {value}")
            bits = pcs_bits.get(idx, {})
            if bits:
                lines.append("    bits:")
                for word, bitset in bits.items():
                    lines.append(f"      {word}: [{', '.join(str(b) for b in sorted(bitset))}]")

    if emu_bits:
        lines.append("emu:")
        lines.append("  bits:")
        for word, bitset in emu_bits.items():
            lines.append(f"    {word}: [{', '.join(str(b) for b in sorted(bitset))}]")

    lines.append("")
    lines.extend(notes)
    return "\n".join(lines) + "\n"


def write_injection_yaml(path, rule_ids, use_alt=None):
    """Writes yaml_text_for(...)'s output to `path` (the LOCAL Fractal
    simulator's own faults YAML file for whichever site it's running --
    caller-provided, since each teammate has their own). Overwrites the
    whole file -- this is meant for a single-purpose local test fixture,
    not for merging with unrelated hand-edits already in that file."""
    text = yaml_text_for(rule_ids, use_alt=use_alt)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    return text


def clear_injection_yaml(path):
    """Writes an empty (no overrides) YAML file -- turns off every
    injected condition, same intent as alarms/inject.py --clear for EPC."""
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("# cleared by shared/domain/fractal_injection.py\npcs: {}\nemu: {}\n")


def _self_check():
    print("(fractal injection YAML generation test — pure logic, no filesystem)\n")
    ok = True

    def check(desc, got, exp):
        nonlocal ok
        good = got == exp
        ok = ok and good
        print(f"  {desc:50} {'OK' if good else f'FAIL got={got!r} exp={exp!r}'}")

    # alarm 46: PCS Ground Fault, pcs_index=1, bits alarm_word_4 bit4
    text = yaml_text_for([46])
    check("alarm 46 produces a pcs: 1: bits: block", "pcs:" in text and "1:" in text, True)
    check("alarm 46 sets alarm_word_4 bit4", "alarm_word_4: [4]" in text, True)

    # alarm 38 (vdc analog) + alarm 46 (bits) on the SAME pcs_index=1 should merge
    text2 = yaml_text_for([38, 46])
    check("merged analog+bits on pcs 1", "vdc: 950" in text2 and "alarm_word_4: [4]" in text2, True)

    # alarm 37 needs BOTH bit0 and bit1 combined into one list
    text3 = yaml_text_for([37])
    check("alarm 37 combines bit0+bit1", "alarm_word_29: [0, 1]" in text3, True)

    # alarm 52 is EMU-level (no pcs_index) -> emu: bits: block
    text4 = yaml_text_for([52])
    check("alarm 52 produces an emu: bits: block", "emu:" in text4 and "status_word_3: [0, 1, 2]" in text4, True)

    # alarm 70's inject_alt variant uses the EMU path instead of the PCS one
    text5 = yaml_text_for([70], use_alt={70})
    check("alarm 70 inject_alt uses EMU alarm_word_1", "alarm_word_1: [5]" in text5, True)
    check("alarm 70 inject_alt does NOT use the PCS path", "alarm_word_6" not in text5, True)

    # unknown alarm id raises, doesn't silently no-op
    try:
        yaml_text_for([9999])
        check("unknown alarm id raises KeyError", False, True)
    except KeyError:
        check("unknown alarm id raises KeyError", True, True)

    print("\n=> " + ("ALL OK" if ok else "DIFFERENCES FOUND"))
    return ok


if __name__ == "__main__":
    import sys
    if "--self-check" in sys.argv:
        sys.exit(0 if _self_check() else 1)
